#!/usr/bin/env python3
"""Generate the theme stylesheets from tokens/tokens.json.

tokens/tokens.json is the single source for the palette. This script writes:

  assets/css/theme-<variant>.css   one per variant, consumed by Hugo/Relearn
  tokens/dist/tokens.css           every variant's --wf-* palette in one file,
                                   for consumers outside this repo

    python3 scripts/gen-tokens.py            write the files
    python3 scripts/gen-tokens.py --check    exit 1 if any file on disk differs
                                             from what tokens.json generates

Nobody hand-edits theme-*.css or tokens/dist/tokens.css. Edit tokens.json,
run this, commit both. Structure of tokens.json: tokens/README.md.

Standard library only, like the rest of scripts/.
"""
import json
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tokens" / "tokens.json"
CSS_DIR = ROOT / "assets" / "css"
DIST = ROOT / "tokens" / "dist" / "tokens.css"
NS = "csc"            # $extensions key holding everything that is ours
WIDTH = 78            # comment / font-list wrap column
TRAIL_MAX = 100       # longest line a trailing /* comment */ may make
BANNER = "GENERATED by scripts/gen-tokens.py from tokens/tokens.json. Do not edit by hand."


class TokenError(Exception):
    pass


def ext(node):
    return node.get("$extensions", {}).get(NS, {})


def load():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    variants = list(ext(data)["variants"])
    tops = {k: v for k, v in data.items() if not k.startswith("$")}
    # css name for every token path, and the flat token list in file order
    tokens, byname, byalias = [], {}, {}

    def walk(node, path, prefix, groups):
        for key, child in node.items():
            if key.startswith("$"):
                continue
            if "$value" in child:
                name = "--" + prefix + key
                if name in byname:
                    raise TokenError(f"duplicate css name {name}")
                tok = {"name": name, "path": ".".join(path + [key]), "node": child,
                       "groups": groups, "top": path[0]}
                tokens.append(tok)
                byname[name] = tok
                byalias[tok["path"]] = tok
            else:
                walk(child, path + [key], prefix, groups + [child])

    for top, node in tops.items():
        walk(node, [top], ext(node)["cssPrefix"], [node])
    return data, variants, tops, tokens, byalias


def applies(tok, variant):
    only = ext(tok["node"]).get("only")
    return only is None or variant in only


def pick(node, variants, variant, field):
    """Value of $value / $description for one variant: the override if there is
    one, else the base (the first variant the token applies to)."""
    over = ext(node).get("variants", {}).get(variant, {})
    return over[field] if field in over else node.get(field)


def fmt_value(value, byalias):
    if isinstance(value, list):                       # fontFamily
        return [f'"{v}"' if re.search(r"\s", v) else v for v in value]
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return [("%g" % value)]
    m = re.fullmatch(r"\{([^{}]+)\}", value)
    if m:
        target = byalias.get(m.group(1))
        if target is None:
            raise TokenError(f"alias {value} points at nothing")
        return [f"var( {target['name']} )"]
    return [value]


def comment(text, indent):
    """A /* ... */ block, wrapped to WIDTH."""
    if "*/" in text:
        raise TokenError(f"description contains a comment terminator: {text[:40]}")
    pad = " " * indent
    lines = textwrap.wrap(text, WIDTH - indent - 3, break_long_words=False,
                          break_on_hyphens=False)
    out = []
    for i, ln in enumerate(lines):
        out.append(pad + ("/* " if i == 0 else "   ") + ln)
    out[-1] += " */"
    return out


def wrap_items(prefix, items):
    """Greedy-fill comma separated items under `prefix`, continuation aligned."""
    lines, cur = [], prefix
    ind = " " * len(prefix)
    for i, it in enumerate(items):
        piece = it + ("," if i < len(items) - 1 else ";")
        if cur.strip() and len(cur) + len(piece) + 1 > WIDTH and cur != prefix:
            lines.append(cur.rstrip())
            cur = ind
        cur += piece + " "
    lines.append(cur.rstrip())
    return lines


def header_block(text):
    lines = text.split("\n")
    out = ["/* " + lines[0], " *", " * " + BANNER]
    for ln in lines[1:]:
        out.append((" * " + ln).rstrip() if ln else " *")
    out.append(" */")
    return out


def emit_variant(variants, tokens, byalias, variant, only_tops=None):
    """Body lines (the :root { ... } contents) for one variant."""
    live = [t for t in tokens
            if applies(t, variant) and (not only_tops or t["top"] in only_tops)]
    widths = {}
    for t in live:
        g = id(t["groups"][-1])
        widths[g] = max(widths.get(g, 0), len(t["name"]) + 2)
    out, opened = [], set()
    for tok in live:
        group = tok["groups"][-1]
        if id(group) not in opened:
            # the top-level group's banner (if any) goes once, before its
            # first sub-group; then the sub-group's own
            for g in (tok["groups"][0], group):
                if id(g) in opened:
                    continue
                opened.add(id(g))
                text = pick(g, variants, variant, "$description")
                if text:
                    out += ([""] if out else []) + comment("---- " + text + " ----", 2)
                elif g is group and out:
                    out.append("")
        val = pick(tok["node"], variants, variant, "$value")
        parts = fmt_value(val, byalias)
        prefix = f"  {tok['name'] + ':':<{widths[id(group)]}}"
        if isinstance(val, list):
            body = wrap_items(prefix, parts)
        else:
            body = [prefix + parts[0] + ";"]
        desc = pick(tok["node"], variants, variant, "$description")
        if desc:
            if len(body) == 1 and len(body[0]) + len(desc) + 8 <= TRAIL_MAX:
                body[0] += f"  /* {desc} */"
            else:
                body = comment(desc, 2) + body
        out += body
    return out


def theme_css(data, variants, tops, tokens, byalias, variant):
    text = pick(data, variants, variant, "$description")
    lines = header_block(text) + ["", ":root {"]
    lines += emit_variant(variants, tokens, byalias, variant)
    lines += ["}"]
    return "\n".join(lines) + "\n"


def dist_css(data, variants, tops, tokens, byalias):
    lines = [
        "/* FAU Cybersecurity Club palette: the --wf-* tokens of every theme variant.",
        " *",
        " * " + BANNER,
        " *",
        " * One block per variant, selected by the data-theme-variant attribute on",
        " * <html>. The first variant (hacker, the site default) also answers a bare",
        " * :root, so a page that sets no attribute gets it. Relearn's own --*-color",
        " * map is left out: it only means something inside the wiki.",
        " */",
    ]
    for i, v in enumerate(variants):
        sel = f":root[data-theme-variant='{v}']"
        if i == 0:
            sel = ":root,\n" + sel
        lines += ["", sel + " {"]
        lines += emit_variant(variants, tokens, byalias, v, only_tops={"wf"})
        lines += ["}"]
    return "\n".join(lines) + "\n"


def validate(data, variants, tokens, byalias):
    errs = []
    for tok in tokens:
        node = tok["node"]
        only = ext(node).get("only")
        for v in ext(node).get("variants", {}):
            if v not in variants:
                errs.append(f"{tok['path']}: unknown variant {v!r}")
        if only is not None:
            if any(v not in variants for v in only):
                errs.append(f"{tok['path']}: only lists an unknown variant")
            elif node["$value"] is not None and any(
                    v not in only for v in ext(node).get("variants", {})):
                errs.append(f"{tok['path']}: variants override a variant outside only")
        vals = [pick(node, variants, v, "$value") for v in variants if applies(tok, v)]
        if not vals or any(x is None for x in vals):
            errs.append(f"{tok['path']}: a variant has no value")
        for x in vals:
            for ref in re.findall(r"\{([^{}]+)\}", x) if isinstance(x, str) else []:
                if ref not in byalias:
                    errs.append(f"{tok['path']}: alias {{{ref}}} points at nothing")
    # every wf token must exist in every variant unless it is marked `only`;
    # that rule is AGENTS.md "Adding a theme variant", enforced here
    # (applies() already encodes it: no `only` means all variants).
    # alias cycles
    for tok in tokens:
        seen, cur = set(), tok
        while True:
            val = pick(cur["node"], variants, variants[0] if applies(cur, variants[0])
                       else ext(cur["node"])["only"][0], "$value")
            m = re.fullmatch(r"\{([^{}]+)\}", val) if isinstance(val, str) else None
            if not m or m.group(1) not in byalias:
                break
            if cur["path"] in seen:
                errs.append(f"alias cycle at {tok['path']}")
                break
            seen.add(cur["path"])
            cur = byalias[m.group(1)]
    return errs


def build():
    data, variants, tops, tokens, byalias = load()
    errs = validate(data, variants, tokens, byalias)
    if errs:
        raise TokenError("\n".join(errs))
    files = {}
    for v in variants:
        files[CSS_DIR / f"theme-{v}.css"] = theme_css(data, variants, tops, tokens, byalias, v)
    files[DIST] = dist_css(data, variants, tops, tokens, byalias)
    return files


def main(argv):
    check = "--check" in argv
    if set(argv) - {"--check"}:
        print(__doc__)
        return 2
    try:
        files = build()
    except TokenError as e:
        print(f"tokens.json: {e}", file=sys.stderr)
        return 1
    stale = []
    for path, text in files.items():
        have = path.read_text(encoding="utf-8") if path.exists() else None
        if have != text:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    rel = lambda p: p.relative_to(ROOT)
    if check:
        for p in stale:
            print(f"out of date: {rel(p)}", file=sys.stderr)
        if stale:
            print("run: python3 scripts/gen-tokens.py   (then commit the result)",
                  file=sys.stderr)
            return 1
        print(f"{len(files)} generated files match tokens/tokens.json")
        return 0
    for p in stale:
        print(f"wrote {rel(p)}")
    if not stale:
        print("already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
