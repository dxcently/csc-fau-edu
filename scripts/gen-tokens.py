#!/usr/bin/env python3
"""Generate the theme stylesheets from tokens/tokens.json.

tokens/tokens.json is the single source for the palette. This script writes:

  assets/css/theme-<variant>.css   one per variant, consumed by Hugo/Relearn
  tokens/dist/tokens.css           every variant's --wf-* palette in one file,
                                   for consumers outside this repo
  tokens/dist/authentik.css        the club login / flow pages for Authentik,
                                   dark by default, light under data-theme

    python3 scripts/gen-tokens.py            write the files
    python3 scripts/gen-tokens.py --check    exit 1 if any file on disk differs
                                             from what tokens.json generates

Nobody hand-edits theme-*.css or tokens/dist/tokens.css. Edit tokens.json,
run this, commit both. Structure of tokens.json: tokens/README.md.

Standard library only, like the rest of scripts/.
"""
import json
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tokens" / "tokens.json"
CSS_DIR = ROOT / "assets" / "css"
DIST = ROOT / "tokens" / "dist" / "tokens.css"
AUTHENTIK = ROOT / "tokens" / "dist" / "authentik.css"
NS = "csc"            # $extensions key holding everything that is ours
WIDTH = 78            # comment / font-list wrap column
TRAIL_MAX = 100       # longest line a trailing /* comment */ may make
BANNER = "GENERATED by scripts/gen-tokens.py from tokens/tokens.json. Do not edit by hand."


class TokenError(Exception):
    pass


def ext(node):
    return node.get("$extensions", {}).get(NS, {})


def load(src=SRC):
    data = json.loads(Path(src).read_text(encoding="utf-8"))
    variants = list(ext(data)["variants"])
    tops = {k: v for k, v in data.items() if not k.startswith("$")}
    # css name for every token path, and the flat token list in file order
    tokens, byname, byalias = [], {}, {}

    def walk(node, path, prefix, groups):
        for key, child in node.items():
            if key.startswith("$"):
                continue
            if "$value" in child:
                name = "--" + prefix + key
                if name in byname:
                    raise TokenError(f"duplicate css name {name}")
                tok = {"name": name, "path": ".".join(path + [key]), "node": child,
                       "groups": groups, "top": path[0]}
                tokens.append(tok)
                byname[name] = tok
                byalias[tok["path"]] = tok
            else:
                walk(child, path + [key], prefix, groups + [child])

    for top, node in tops.items():
        walk(node, [top], ext(node)["cssPrefix"], [node])
    return data, variants, tops, tokens, byalias


LITERAL_COLOR = re.compile(r"#[0-9A-Fa-f]{3,8}|(?:rgb|rgba|hsl|hsla)\(.*\)", re.S)


def is_literal_color(value):
    return isinstance(value, str) and LITERAL_COLOR.fullmatch(value) is not None


def applies(tok, variant):
    """Does this token exist in this variant? Yes unless `only` excludes it."""
    only = ext(tok["node"]).get("only")
    return only is None or variant in only


def pick(node, variants, variant, field):
    """Value of $value / $description for one variant: the override if there is
    one, else the base (the first variant the token applies to)."""
    over = ext(node).get("variants", {}).get(variant, {})
    return over[field] if field in over else node.get(field)


def pick_comment(node, variant):
    """The block comment above a token: $extensions.csc.comment, overridable
    per variant like $value and $description."""
    over = ext(node).get("variants", {}).get(variant, {})
    return over["comment"] if "comment" in over else ext(node).get("comment")


def fmt_value(value, byalias):
    if isinstance(value, list):                       # fontFamily
        return [f'"{v}"' if re.search(r"\s", v) else v for v in value]
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return [("%g" % value)]
    m = re.fullmatch(r"\{([^{}]+)\}", value)
    if m:
        target = byalias.get(m.group(1))
        if target is None:
            raise TokenError(f"alias {value} points at nothing")
        return [f"var( {target['name']} )"]
    return [value]


def comment(text, indent):
    """A /* ... */ block, wrapped to WIDTH. In the text, "\\n" starts a new
    line, an empty line is a blank line, and a line beginning "* " is a bullet."""
    if "*/" in text:
        raise TokenError(f"description contains a comment terminator: {text[:40]}")
    pad = " " * indent
    out = []
    for para in text.split("\n"):
        if not para:
            out.append("")
            continue
        bullet = para.startswith("* ")
        lead = indent + 3 + (2 if bullet else 0)
        for ln in textwrap.wrap(para, WIDTH - lead, break_long_words=False,
                                break_on_hyphens=False,
                                subsequent_indent="  " if bullet else ""):
            out.append(" " * lead + ln)
    out[0] = pad + "/* " + out[0].lstrip()
    out[-1] += " */"
    return out


def wrap_items(prefix, items):
    """Greedy-fill comma separated items under `prefix`, continuation aligned."""
    lines, cur = [], prefix
    ind = " " * len(prefix)
    for i, it in enumerate(items):
        piece = it + ("," if i < len(items) - 1 else ";")
        if cur.strip() and len(cur) + len(piece) + 1 > WIDTH and cur != prefix:
            lines.append(cur.rstrip())
            cur = ind
        cur += piece + " "
    lines.append(cur.rstrip())
    return lines


def header_block(text):
    lines = text.split("\n")
    out = ["/* " + lines[0], " *", " * " + BANNER]
    for ln in lines[1:]:
        out.append((" * " + ln).rstrip() if ln else " *")
    out.append(" */")
    return out


def emit_variant(variants, tokens, byalias, variant, only_tops=None):
    """Body lines (the :root { ... } contents) for one variant."""
    live = [t for t in tokens
            if applies(t, variant) and (not only_tops or t["top"] in only_tops)]
    widths = {}
    for t in live:
        g = id(t["groups"][-1])
        widths[g] = max(widths.get(g, 0), len(t["name"]) + 2)
    out, opened = [], set()
    for tok in live:
        group = tok["groups"][-1]
        if id(group) not in opened:
            # the top-level group's banner (if any) goes once, before its
            # first sub-group; then the sub-group's own
            for g in (tok["groups"][0], group):
                if id(g) in opened:
                    continue
                opened.add(id(g))
                text = pick(g, variants, variant, "$description")
                if text:
                    out += ([""] if out else []) + comment("---- " + text + " ----", 2)
                elif g is group and out:
                    out.append("")
        val = pick(tok["node"], variants, variant, "$value")
        parts = fmt_value(val, byalias)
        prefix = f"  {tok['name'] + ':':<{widths[id(group)]}}"
        if isinstance(val, list):
            body = wrap_items(prefix, parts)
        else:
            body = [prefix + parts[0] + ";"]
        desc = pick(tok["node"], variants, variant, "$description")
        if desc:
            if len(body) == 1 and len(body[0]) + len(desc) + 8 <= TRAIL_MAX:
                body[0] += f"  /* {desc} */"
            else:
                body = comment(desc, 2) + body
        block = pick_comment(tok["node"], variant)
        if block:       # a list is several consecutive blocks
            for text in reversed([block] if isinstance(block, str) else block):
                body = comment(text, 2) + body
        out += body
    return out


def theme_css(data, variants, tops, tokens, byalias, variant):
    text = pick(data, variants, variant, "$description")
    lines = header_block(text) + ["", ":root {"]
    lines += emit_variant(variants, tokens, byalias, variant)
    lines += ["}"]
    return "\n".join(lines) + "\n"


def dist_css(data, variants, tops, tokens, byalias):
    lines = [
        "/* FAU Cybersecurity Club palette: the --wf-* tokens of every theme variant.",
        " *",
        " * " + BANNER,
        " *",
        " * One block per variant, selected by the data-r-theme-variant attribute on",
        " * <html>, the attribute the wiki's own switcher sets. The first variant (hacker, the site default) also answers a bare",
        " * :root, so a page that sets no attribute gets it. Relearn's own --*-color",
        " * map is left out: it only means something inside the wiki.",
        " */",
    ]
    for i, v in enumerate(variants):
        sel = f":root[data-r-theme-variant='{v}']"
        if i == 0:
            sel = ":root,\n" + sel
        lines += ["", sel + " {"]
        lines += emit_variant(variants, tokens, byalias, v, only_tops={"wf"})
        lines += ["}"]
    return "\n".join(lines) + "\n"


# Authentik branding. Each row: (authentik variable, wf token path, job).
# Authentik's documented public surface is the semantic --ak-* set
# (docs.goauthentik.io/brands/custom-css); it bridges those into the
# PatternFly --pf-* names its components read. The rows follow the four
# colour jobs: blue is structure (primary action, links, borders), green is
# identity (accent), pale is reading (text). Red appears ONLY as the danger
# state, and only the lifted red-text, never the fill red as text.
AK_VARS = [
    ("--ak-color-accent",        "wf.palette.primary",     "identity green"),
    ("--ak-color-primary",       "wf.palette.chrome",      "structure blue: primary action"),
    ("--ak-color-link",          "wf.palette.chrome-hi",   "structure blue, lifted: links"),
    ("--ak-color-text",          "wf.palette.text",        "reading"),
    ("--ak-color-text-muted",    "wf.palette.text-muted",  "meta"),
    ("--ak-color-surface",       "wf.palette.bg-raised",   "the card and inputs"),
    ("--ak-color-surface-muted", "wf.palette.bg",          "the page ground"),
    ("--ak-color-border",        "wf.palette.chrome",      None),
    ("--ak-color-danger",        "wf.palette.red-text",    "the one red: errors, as text"),
]
# Authentik variants of the club variants: dark is the default.
AK_THEMES = [("hacker", ":root,\nhtml[data-theme='dark']"),
             ("hacker-light", "html[data-theme='light']")]
# PatternFly 4 names Authentik's components read. Not part of its stable API
# (its docs say --pf-* may change), so they sit apart from the --ak-* rows.
AK_PF = [
    ("--pf-c-login__main--BackgroundColor", "var( --ak-color-surface )"),
    ("--pf-c-button--m-primary--BackgroundColor", "var( --ak-color-primary )"),
    ("--pf-c-button--m-primary--Color", "var( --ak-on-primary )"),
    ("--pf-c-form-control--BackgroundColor", "var( --ak-color-surface-muted )"),
    ("--pf-c-form-control--Color", "var( --ak-color-text )"),
    ("--pf-global--BorderColor--100", "var( --ak-color-border )"),
    ("--pf-global--link--Color", "var( --ak-color-link )"),
    ("--pf-global--link--Color--hover", "var( --ak-color-text-strong )"),
    ("--pf-global--primary-color--100", "var( --ak-color-primary )"),
    ("--pf-global--Color--100", "var( --ak-color-text )"),
]


def resolve(tokens, byalias, variants, variant, path):
    """The literal value of one token in one variant, following aliases."""
    if path not in byalias:
        raise TokenError(f"authentik.css needs token {path}, which tokens.json lacks")
    tok = byalias[path]
    while True:
        val = pick(tok["node"], variants, variant, "$value")
        m = re.fullmatch(r"\{([^{}]+)\}", val) if isinstance(val, str) else None
        if not m:
            return val
        tok = byalias[m.group(1)]


def authentik_css(data, variants, tokens, byalias):
    lines = [
        "/* FAU Cybersecurity Club sign-in pages: Authentik brand custom CSS.",
        " *",
        " * " + BANNER,
        " *",
        " * Paste into System > Brands > Custom CSS. Dark is the default (set the",
        " * brand attribute settings.theme.base: dark to enforce it); the light block",
        " * answers html[data-theme='light'] and is the club's daylight palette.",
        " * It sets Authentik's own --ak-* variables, which its docs call the public",
        " * surface, then the PatternFly --pf-* names its components read. The",
        " * --pf-* block is the fragile half: check it after every Authentik upgrade.",
        " * Colour jobs as on the site: blue is structure, green is identity, pale is",
        " * reading. Red is only the error state.",
        " */",
    ]
    for variant, sel in AK_THEMES:
        r = lambda path: resolve(tokens, byalias, variants, variant, path)
        lines += ["", sel + " {", "  color-scheme: " + ("light" if variant == "hacker-light" else "dark") + ";"]
        for name, path, note in AK_VARS:
            lines.append(f"  {name + ':':<27}{r(path)};" + (f"  /* {note} */" if note else ""))
        lines.append(f"  {'--ak-color-text-strong:':<27}{r('wf.palette.text-strong')};  /* headings, hover */")
        lines.append(f"  {'--ak-on-primary:':<27}{r('wf.palette.bg')};  /* text on the blue fill */")
        lines.append(f"  {'--ak-radius-sm:':<27}{r('wf.geometry.radius')};  /* near-square, like the site */")
        fonts = ", ".join(fmt_value(pick(byalias["wf.type.font-sans"]["node"], variants, variant, "$value"), byalias))
        lines.append(f"  {'--ak-font-family-sans-serif:':<27} {fonts};")
        lines.append("")
        for name, val in AK_PF:
            lines.append(f"  {name + ':':<46}{val};")
        lines += ["}"]
    lines += ["", "/* Keyboard focus: the structure blue, lifted. Document level only; inside",
              " * Authentik's shadow roots this does not reach, and its own focus colour",
              " * follows --pf-global--primary-color--100 above. */",
              ":where(a, button, input, select, textarea, [tabindex]):focus-visible {",
              "  outline: 2px solid var( --ak-color-link );",
              "  outline-offset: 2px;",
              "}",
              "",
              "/* Page ground under the card. The flow background image, if the flow sets",
              " * one, paints over this. */",
              "html, body {",
              "  background-color: var( --ak-color-surface-muted );",
              "}"]
    return "\n".join(lines) + "\n"


def colour_rule(variants, tok):
    """A literal colour (#hex, rgb(), rgba(), hsl()) must be decided in every
    variant it applies to: the variant gives its own `$value`, or is listed in
    `$extensions.csc.inherit` as deliberately the base's colour. Aliases and
    non-colour tokens are not subject to this; they fall back to the base."""
    node, path = tok["node"], tok["path"]
    live = [v for v in variants if applies(tok, v)]
    if not live:
        return []
    base, rest = live[0], live[1:]
    over = ext(node).get("variants", {})
    inherit = ext(node).get("inherit", [])
    errs = []
    for v in inherit:
        if v not in rest:
            errs.append(f"{path}: inherit lists {v!r}, which is not a non-base variant "
                        "this token applies to")
        elif "$value" in over.get(v, {}):
            errs.append(f"{path}: {v!r} is in inherit but also overrides $value")
    if not is_literal_color(node["$value"]):
        if inherit:
            errs.append(f"{path}: inherit only applies to literal colours")
        return errs
    for v in rest:
        if "$value" in over.get(v, {}):
            if over[v]["$value"] == node["$value"]:
                errs.append(f"{path}: {v!r} overrides $value with the base's own value; "
                            "list it in inherit instead")
        elif v not in inherit:
            errs.append(f"{path}: no colour for variant {v!r}; give variants.{v}.$value "
                        f"or list {v!r} in $extensions.{NS}.inherit")
    return errs


def validate(variants, tokens, byalias):
    errs = []
    for tok in tokens:
        node, path = tok["node"], tok["path"]
        only = ext(node).get("only")
        for v in ext(node).get("variants", {}):
            if v not in variants:
                errs.append(f"{path}: unknown variant {v!r}")
            elif only is not None and v not in only:
                errs.append(f"{path}: overrides {v!r}, which `only` excludes")
        if only is not None and any(v not in variants for v in only):
            errs.append(f"{path}: `only` lists an unknown variant")
        errs += colour_rule(variants, tok)
    # Per variant: every live token has a value, every alias resolves, and no
    # alias chain loops.
    for v in variants:
        for tok in tokens:
            if not applies(tok, v):
                continue
            seen, cur = set(), tok
            while True:
                val = pick(cur["node"], variants, v, "$value")
                if val is None:
                    errs.append(f"{cur['path']}: no value for {v!r}")
                    break
                m = re.fullmatch(r"\{([^{}]+)\}", val) if isinstance(val, str) else None
                if not m:
                    break
                target = byalias.get(m.group(1))
                if target is None:
                    errs.append(f"{cur['path']}: alias {val} points at nothing")
                    break
                if not applies(target, v):
                    errs.append(f"{cur['path']}: alias {val} has no value in {v!r}")
                    break
                if target["path"] in seen or target is tok:
                    errs.append(f"alias cycle at {tok['path']} in {v!r}")
                    break
                seen.add(target["path"])
                cur = target
    return errs


def build(src=SRC):
    data, variants, tops, tokens, byalias = load(src)
    errs = validate(variants, tokens, byalias)
    if errs:
        raise TokenError("\n".join(errs))
    files = {}
    for v in variants:
        files[CSS_DIR / f"theme-{v}.css"] = theme_css(data, variants, tops, tokens, byalias, v)
    files[DIST] = dist_css(data, variants, tops, tokens, byalias)
    # The Authentik sheet names real club tokens, so it only makes sense for
    # the club's own tokens.json (the unit tests build from tiny fixtures).
    if Path(src).resolve() == SRC:
        files[AUTHENTIK] = authentik_css(data, variants, tokens, byalias)
    return files


def main(argv):
    check = "--check" in argv
    if set(argv) - {"--check"}:
        print(__doc__)
        return 2
    try:
        files = build()
    except TokenError as e:
        print(f"tokens.json: {e}", file=sys.stderr)
        return 1
    stale = []
    # a theme-*.css with no matching variant is a leftover (or a variant that
    # was never added to tokens.json); tokens.json does not own it
    strays = [p for p in sorted(CSS_DIR.glob("theme-*.css")) if p not in files]
    for path, text in files.items():
        have = path.read_text(encoding="utf-8") if path.exists() else None
        if have != text:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    rel = lambda p: p.relative_to(ROOT)
    if check:
        for p in stale:
            print(f"out of date: {rel(p)}", file=sys.stderr)
        for p in strays:
            print(f"no variant in tokens.json: {rel(p)} (delete it or add the variant)",
                  file=sys.stderr)
        if stale or strays:
            print("run: python3 scripts/gen-tokens.py   (then commit the result)",
                  file=sys.stderr)
            return 1
        print(f"{len(files)} generated files match tokens/tokens.json")
        return 0
    for p in strays:
        print(f"warning: {rel(p)} matches no variant in tokens.json", file=sys.stderr)
    for p in stale:
        print(f"wrote {rel(p)}")
    if not stale:
        print("already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
